function spawnCapture(argv, { cwd, env, timeoutSeconds = 600 }) {
  return new Promise((resolve, reject) => {
    const child = spawn(argv[0], argv.slice(1), {
      cwd,
      env,
      stdio: ['ignore', 'pipe', 'pipe'],
      shell: process.platform === 'win32',
    });
    let stdout = '';
    let stderr = '';
    child.stdout?.on('data', (d) => (stdout += d));
    child.stderr?.on('data', (d) => (stderr += d));
    const timer = setTimeout(() => {
      child.kill('SIGTERM');
      reject(new Error(`Timed out after ${timeoutSeconds}s`));
    }, timeoutSeconds * 1000);
    child.on('close', (code) => {
      clearTimeout(timer);
      resolve({ code: code ?? 1, stdout, stderr });
    });
    child.on('error', reject);
  });
}

/**
 * Check whether Playwright can run. Does not install — returns hints for the
 * engineer when something is missing.
 */
export async function preflightPlaywright(repoRoot) {
  const problems = [];
  if (!existsSync(join(repoRoot, 'package.json'))) problems.push('no package.json');
  if (!hasPlaywrightDep(repoRoot)) problems.push('missing devDependency @playwright/test');
  const scripts = readPackageScripts(repoRoot);
  if (!scripts['test:e2e']) problems.push('missing npm script test:e2e');
  if (problems.length) {
    return { ok: false, problems, installHint: preflightInstallHint() };
  }
  try {
    const probe = await spawnCapture(['npx', 'playwright', '--version'], {
      cwd: repoRoot,
      env: process.env,
      timeoutSeconds: 60,
    });
    if (probe.code !== 0) problems.push('playwright CLI unavailable');
  } catch (err) {
    problems.push(String(err.message || err));
  }
  return {
    ok: problems.length === 0,
    problems,
    installHint: problems.length ? preflightInstallHint() : null,
  };
}

export function preflightInstallHint() {
  return 'npm install -D @playwright/test && npx playwright install chromium';
}

// ── unchanged-retry guard ────────────────────────────────────────────────────
// A failed e2e re-run with ZERO repo changes cannot pass — but a resumed run
// happily re-executes it (and everything after it) anyway. The fingerprint
// and marker machinery lives in modules/tree-guard.mjs (shared with the /qa
// audit, ui_verify and the bare-resume guard); these wrappers keep the
// e2e-attempts.json marker name and the e2e-specific refusal message.

const E2E_ATTEMPT = 'e2e';

/** The recorded last failure — { stamp, count, at } — or null. */
export function readE2eAttempt(artifactDir) {
  return readAttempt(artifactDir, E2E_ATTEMPT);
}

/** Record a failure under this stamp; a NEW stamp restarts the count at 1. */
export function recordE2eFailure(artifactDir, stamp) {
  return recordAttemptFailure(artifactDir, E2E_ATTEMPT, stamp);
}

export function clearE2eAttempt(artifactDir) {
  clearAttempt(artifactDir, E2E_ATTEMPT);
}

/**
 * The refusal message when re-running e2e is provably futile, or null when
 * the attempt should proceed: first try, the repo changed since the failure,
 * no fingerprint available, or the engineer overrode with --retry-unchanged.
 */
export function unchangedRetryError({ prior, stamp, fdaId, artifactRelDir, override = false }) {
  if (override || !stamp || !prior || prior.stamp !== stamp) return null;
  return (
    `Playwright e2e already failed ${prior.count === 1 ? 'once' : `${prior.count} times`} on this exact tree — nothing changed in the repo since, so re-running cannot pass.\n` +
    `Fix the app or the tests first (log: ${artifactRelDir}/playwright.log), then resume:\n` +
    `  node imp/fda_qa.mjs --resume --fda-id ${fdaId}\n` +
    'Genuinely flaky suite? Re-run explicitly with --retry-unchanged.'
  );
}

/**
 * Idempotent project setup: deps, config, e2e dir, test:e2e script.
 * Mutates the student project — never aborts the CLI install.
 */
export async function ensurePlaywrightSetup(repoRoot, { artifactRelDir, videoPolicy }) {
  mkdirSync(join(repoRoot, artifactRelDir), { recursive: true });
  mkdirSync(join(repoRoot, 'e2e'), { recursive: true });

  if (!hasPlaywrightDep(repoRoot)) {
    const install = await spawnCapture(['npm', 'install', '-D', '@playwright/test'], {
      cwd: repoRoot,
      env: process.env,
      timeoutSeconds: 300,
    });
    if (install.code !== 0) {
      throw new Error(
        `failed to install @playwright/test:\n${install.stderr.slice(-2000)}\nRun manually: ${preflightInstallHint()}`,
      );
    }
  }

  const browsers = await spawnCapture(['npx', 'playwright', 'install', 'chromium'], {
    cwd: repoRoot,
    env: process.env,
    timeoutSeconds: 600,
  });
  if (browsers.code !== 0) {
    throw new Error(
      `failed to install Chromium for Playwright:\n${browsers.stderr.slice(-2000)}\nRun manually: npx playwright install chromium`,
    );
  }

  const configPath = join(repoRoot, PLAYWRIGHT_CONFIG);
  if (!existsSync(configPath)) {
    writeFileSync(configPath, playwrightConfigTemplate(), 'utf8');
  }

  const pkgPath = join(repoRoot, 'package.json');
  const pkg = JSON.parse(readFileSync(pkgPath, 'utf8'));
  pkg.scripts = pkg.scripts || {};
  if (!pkg.scripts['test:e2e']) {
    pkg.scripts['test:e2e'] = 'playwright test';
    writeFileSync(pkgPath, `${JSON.stringify(pkg, null, 2)}\n`, 'utf8');
  }

  return { configPath: PLAYWRIGHT_CONFIG, videoPolicy, artifactRelDir };
}

export async function runPlaywrightE2e(run, { artifactRelDir, videoPolicy }) {
  const outputDir = join(run.repoRoot, artifactRelDir);
  mkdirSync(outputDir, { recursive: true });
  const logPath = join(outputDir, 'playwright.log');
  const phase = run.phases.at(-1);
  const startedAt = nowIso();
  const command = 'npm run test:e2e';
  run.console.note(`qa e2e: ${command} (video=${videoPolicy})`);

  const env = {
    ...run.env,
    FIA_QA_OUTPUT: artifactRelDir,
    FIA_QA_VIDEO: videoPolicy,
  };

  let returncode = 0;
  let stdout = '';
  let stderr = '';
  try {
    const result = await spawnCapture(['npm', 'run', 'test:e2e'], {
      cwd: run.repoRoot,
      env,
      timeoutSeconds: 900,
    });
    returncode = result.code;
    stdout = result.stdout;
    stderr = result.stderr;
  } catch (err) {
    returncode = 124;
    stderr = String(err.message || err);
  }

  const logBody = `$ ${command}\nexit: ${returncode}\nvideo: ${videoPolicy}\noutput: ${artifactRelDir}\n\n--- stdout ---\n${stdout}\n--- stderr ---\n${stderr}\n`;
  writeFileSync(logPath, logBody, 'utf8');

  run.tracer.event({
    fda_id: run.fdaId,
    phase_id: phase?.phase_id,
    type: 'tool_call',
    name: 'qa:e2e',
    payload: {
      command,
      returncode,
      passed: returncode === 0,
      output_artifact: logPath,
      artifact_dir: artifactRelDir,
    },
    started_at: startedAt,
    ended_at: nowIso(),
  });

  const passed = returncode === 0;
  const tail = (stdout + stderr).slice(-4000);
  return {
    passed,
    returncode,
    output_artifact: logPath,
    artifactRelDir,
    output_tail: tail,
    failures: passed ? [] : [`e2e: \`${command}\` exited ${returncode}\n${tail}`.trim()],
  };
}
